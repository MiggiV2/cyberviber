const int N_THEMES = sizeof(THEMES) / sizeof(THEMES[0]);

int findTheme(const char* id) {
  if (!id) return -1;
  for (int i = 0; i < N_THEMES; i++)
    if (!strcmp(THEMES[i].id, id)) return i;
  return -1;
}

int findLayout(const char* id) {
  if (!id) return -1;
  for (int i = 0; i < N_LAYOUTS; i++)
    if (!strcmp(LAYOUTS[i].id, id)) return i;
  return -1;
}
